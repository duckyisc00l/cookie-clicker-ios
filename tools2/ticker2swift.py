# Translates the original game's news ticker (G.getTicker in main.js) into Swift.
import re,sys
src=open(sys.argv[1]).read().split('\n')
start=next(i for i,l in enumerate(src) if 'G.getTicker=function()' in l)
end=next(i for i,l in enumerate(src) if i>start and "G.Has('Fortune cookies')" in l)
body='\n'.join(src[start+2:end])  # skip "G.getTicker=function()" and "{"
# --- tokenize: strings, comments, code
out=[];i=0;n=len(body)
def swiftstr(s):
    s=s.replace('\\','\\\\').replace('"','\\"')
    s=s.replace("\\\\'","'").replace('\\\\"','\\"')
    return '"'+s+'"'
while i<n:
    c=body[i]
    if body.startswith('//',i):
        j=body.find('\n',i); i=n if j<0 else j; continue
    if body.startswith('/*',i):
        j=body.find('*/',i); i=j+2; continue
    if c in "'\"`":
        q=c;j=i+1;buf=''
        while body[j]!=q:
            if body[j]=='\\': buf+=body[j:j+2]; j+=2; continue
            buf+=body[j]; j+=1
        # unescape JS escapes for quotes
        buf=buf.replace("\\'","'").replace('\\"','"')
        out.append(('S',buf)); i=j+1; continue
    out.append(('C',c)); i+=1
# rebuild with placeholders for strings
code='';strs=[]
for t,v in out:
    if t=='S': strs.append(v); code+='\x00%d\x00'%(len(strs)-1)
    else: code+=v
R=[(r"G\.getSet\(\x00(\d+)\x00\)",lambda m:'G.getSetB('+swiftstr(strs[int(m.group(1))])+')'),
   (r"G\.hasAchiev\(",'G.HasAchiev('),
   (r"Math\.random\(\)",'rnd()'),(r"Math\.floor\(",'floor('),(r"Math\.ceil\(",'ceil('),
   (r"\bvar\b",'var'),(r"\.length\b",'.count'),(r"===",'=='),(r"!==",'!=')]
for a,b in R: code=re.sub(a,b,code)
# list.push(a,b,...) -> list.append(contentsOf:[a,b,...])
def fixcalls(code):
    res='';i=0
    while True:
        j=code.find('list.push(',i)
        if j<0: res+=code[i:]; break
        res+=code[i:j]; k=j+len('list.push('); depth=1;m=k
        while depth:
            if code[m] in '([{': depth+=1
            elif code[m] in ')]}': depth-=1
            m+=1
        res+='list.append(contentsOf:['+code[k:m-1]+'])'; i=m
    return res
code=fixcalls(code)
# if (cond) stmt;  ->  if cond { stmt }   (also else if / else)
def braces(code):
    res='';i=0;L=len(code)
    while i<L:
        m=re.match(r'(else\s+)?if\s*\(',code[i:]) if (i==0 or not (code[i-1].isalnum() or code[i-1]=='_')) else None
        if m:
            k=i+m.end();depth=1;p=k
            while depth:
                if code[p]=='(': depth+=1
                elif code[p]==')': depth-=1
                p+=1
            cond=code[k:p-1]
            res+=(m.group(1) or '')+'if '+cond+' '
            q=p
            while code[q] in ' \t\n': q+=1
            if code[q]=='{': i=q; continue
            # single statement until ; at depth 0
            depth=0;r=q
            while True:
                ch=code[r]
                if ch in '([{': depth+=1
                elif ch in ')]}': depth-=1
                elif ch==';' and depth==0: break
                r+=1
            res+='{ '+braces(code[q:r])+' }'; i=r+1; continue
        m=re.match(r'else\b',code[i:]) if (i==0 or not code[i-1].isalnum()) else None
        if m and not re.match(r'else\s+if',code[i:]):
            q=i+4
            while code[q] in ' \t\n': q+=1
            if code[q]=='{': res+='else '; i=q; continue
            depth=0;r=q
            while True:
                ch=code[r]
                if ch in '([{': depth+=1
                elif ch in ')]}': depth-=1
                elif ch==';' and depth==0: break
                r+=1
            res+='else { '+braces(code[q:r])+' }'; i=r+1; continue
        res+=code[i]; i+=1
    return res
code=braces(code)
code=code.replace(';','')
code=re.sub(r'\x00(\d+)\x00',lambda m:swiftstr(strs[int(m.group(1))]),code)
# the lore line computed by hand
code=re.sub(r'var loreProgress=.*','let loreProgress = jsInt32(log(cookies / 10) * log10(M_E) + 1)',code)
code=code.replace('var list=[]','var list: [String] = []')
code=re.sub(r'\+floor\(((?:[^()]|\([^()]*\))*)\)\+',lambda m:'+jsString(floor('+m.group(1)+'))+',code)
code=re.sub(r'var animals=\[','let animals: [String] = [',code)
code=re.sub(r'var cookies=G\.cookiesEarned','let cookies = G.cookiesEarned',code)
swift='''// Generated by tools2/ticker2swift.py from the original game's news ticker (G.getTicker in www/main.js,
// up to the fortune cookies part, which is in Ticker.swift). Do not edit by hand.
import Foundation

extension Game {
    func generatedNews() -> [String] {
''' + code + '''
        return list
    }
}
'''
open(sys.argv[2],'w').write(swift)
print('ok',len(swift))
